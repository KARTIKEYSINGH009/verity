import pytest
from fastapi.testclient import TestClient

from verity import gateway
from verity.egress import scan_output
from verity.gateway import app


# ---------------------------------------------------------------- module ---

def test_clean_output_allowed_unchanged():
    r = scan_output("Hello, your order shipped yesterday.")
    assert r["action"] == "allow"
    assert r["text"] == "Hello, your order shipped yesterday."
    assert r["findings"] == []


def test_canary_in_output_blocks():
    r = scan_output("The secret is CANARY-7F3A9, do not share it.",
                    canaries={"CANARY-7F3A9"})
    assert r["action"] == "block"
    assert r["text"] == ""
    assert "canary" in r["findings"]


def test_non_allowlisted_url_blocks_and_allowlisted_passes():
    r = scan_output("See https://evil.example.com/steal for details")
    assert r["action"] == "block"
    assert "url:evil.example.com" in r["findings"]
    r = scan_output("See https://shop.example.com/help",
                    allowed_url_hosts={"shop.example.com"})
    assert r["action"] == "allow"


def test_email_redacted():
    r = scan_output("Contact me at priya@example.com please.")
    assert r["action"] == "redact"
    assert r["text"] == "Contact me at [redacted] please."
    assert "email" in r["findings"]


def test_phone_redacted_including_bare_indian_mobile():
    assert scan_output("Call 9876543210")["action"] == "redact"
    assert scan_output("Call 98765 43210")["text"] == "Call [redacted]"
    assert scan_output("Call +91 98765 43210")["action"] == "redact"
    assert scan_output("Call 022-1234-5678")["action"] == "redact"


def test_card_number_redacted():
    r = scan_output("Card 4111 1111 1111 1111 was charged.")
    assert r["action"] == "redact"
    assert r["text"] == "Card [redacted] was charged."
    assert "card" in r["findings"]


def test_block_beats_redact():
    r = scan_output("Leaked CANARY-7F3A9, reach me at a@b.com",
                    canaries={"CANARY-7F3A9"})
    assert r["action"] == "block"
    assert r["text"] == ""
    assert "canary" in r["findings"]


