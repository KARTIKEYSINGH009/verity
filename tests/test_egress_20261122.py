@pytest.fixture(autouse=True)
def _clean_gateway_state():
    gateway._hits.clear()
    yield
    gateway._hits.clear()


def test_url_in_mock_reply_blocked_via_gateway():
    # The mock completion echoes the user message, so a URL in the
    # message comes back in the reply and the egress guard must stop it.
    with TestClient(app) as c:
        r = c.post("/v1/chat/completions", json={
            "model": "gpt-4o-mini",
            "messages": [{"role": "user",
                          "content": "See https://evil.example.com/x"}],
        })
    assert r.status_code == 400
    detail = r.json()["detail"]
    assert detail["error"] == "blocked_by_verity_egress"
    assert "url:evil.example.com" in detail["findings"]


def test_email_in_mock_reply_redacted_via_gateway():
    with TestClient(app) as c:
        r = c.post("/v1/chat/completions", json={
            "model": "gpt-4o-mini",
            "messages": [{"role": "user",
                          "content": "Contact me at priya@example.com"}],
        })
    assert r.status_code == 200
    content = r.json()["choices"][0]["message"]["content"]
    assert "priya@example.com" not in content
    assert "[redacted]" in content
    assert "egress_redacted" in r.json()["verity"]["guard_flags"]


def test_canary_in_mock_reply_blocked_via_gateway(monkeypatch):
    monkeypatch.setattr(gateway.config, "EGRESS_CANARIES",
                        ("CANARY-7F3A9",))
    with TestClient(app) as c:
        r = c.post("/v1/chat/completions", json={
            "model": "gpt-4o-mini",
            "messages": [{"role": "user",
                          "content": "The code is CANARY-7F3A9"}],
        })
    assert r.status_code == 400
    assert r.json()["detail"]["error"] == "blocked_by_verity_egress"
